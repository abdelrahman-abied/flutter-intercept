let seq = 0;
function ex(method: string, url: string, status: number | undefined, body?: string | { b64: string }, extra: Partial<Exchange> = {}): Exchange {
  return {
    id: String(++seq),
    startedAt: 0,
    method,
    url,
    requestHeaders: {},
    status,
    responseHeaders: { 'content-type': 'application/json' },
    responseBody: body === undefined ? undefined : typeof body === 'string' ? { text: body, encoding: 'utf8' } : { text: body.b64, encoding: 'base64' },
    state: status === undefined ? 'error' : 'completed',
    ...extra,
  };
}

