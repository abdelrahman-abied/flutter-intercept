export const PALETTES: Record<IdeTheme, Palette> = { dark, light, 'high-contrast': highContrast };

/** The VS Code body class matching an IDE theme (some webview CSS keys off it). */
export function vscodeBodyClass(theme: IdeTheme): string {
  return theme === 'light' ? 'vscode-light' : theme === 'high-contrast' ? 'vscode-high-contrast' : 'vscode-dark';
}

function block(selector: string, vars: Record<string, string>): string {
  return `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}`;
}

/** The whole stylesheet: font variables, one block per theme (dark is also the default), base styles. */
